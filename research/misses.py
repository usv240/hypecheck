"""Every mistake at the strict threshold, listed by direction, with the sentence and its score.

    python research/misses.py --wa-dir data     # writes results/misses/{dangerous,needless}.csv and MISSES.md

Two kinds of miss, and they are not equal:
- dangerous: an exaggeration the gate let through (false OK);
- needless: a faithful release the gate blocked (false BLOCK), the cost of safety.

Credit for the device: evidence-first, Which Brain? and StipGate list every miss by direction.
"""

from __future__ import annotations

import argparse
import csv
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
R = HERE / "results"
OUT = R / "misses"
LEVELS = ["no relationship", "linked", "may cause", "causes"]
BLOCK = json.loads((R / "calibration" / "summary.json").read_text())["by_alpha"]["0.1"]["threshold"]


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--wa-dir", type=Path, required=True)
    a = ap.parse_args()
    test = [json.loads(x) for x in (a.wa_dir / "test.jsonl").read_text(encoding="utf-8").splitlines() if x.strip()]
    dec = list(csv.DictReader((R / "spike-v1" / "wa_items.csv").open(encoding="utf-8")))
    assert [r["id"] for r in dec] == [t["original_file_id"] for t in test]
    rows = []
    for r, t in zip(dec, test):
        p = float(r["v2_p_exag"])
        flagged = p > BLOCK
        kind = ("dangerous" if r["gold"] == "exaggerates" and not flagged else
                "needless" if r["gold"] == "same" and flagged else
                "downplay_flagged" if r["gold"] == "downplays" and flagged else None)
        if kind:
            rows.append({"kind": kind, "id": r["id"], "gold": r["gold"], "overclaim": round(p, 3),
                         "decider_paper": LEVELS[int(r["v2_abs_strength"])], "decider_release": LEVELS[int(r["v2_pr_strength"])],
                         "expert_paper": LEVELS[int(t["abstract_strength"])],      # W&A labels are 0..3 on the same ladder
                         "expert_release": LEVELS[int(t["press_release_strength"])],
                         "paper": t["abstract_conclusion"].strip(), "release": t["press_release_conclusion"].strip()})
    OUT.mkdir(exist_ok=True)
    for kind in ("dangerous", "needless", "downplay_flagged"):
        sub = sorted((x for x in rows if x["kind"] == kind), key=lambda x: -x["overclaim"] if kind != "dangerous" else x["overclaim"])
        with (OUT / f"{kind}.csv").open("w", newline="", encoding="utf-8") as f:
            w = csv.DictWriter(f, fieldnames=list(rows[0])); w.writeheader(); w.writerows(sub)
    n = {k: sum(x["kind"] == k for x in rows) for k in ("dangerous", "needless", "downplay_flagged")}
    exag = sum(r["gold"] == "exaggerates" for r in dec); same = sum(r["gold"] == "same" for r in dec)

    def table(kind, limit, order_note):
        sub = sorted((x for x in rows if x["kind"] == kind), key=lambda x: -x["overclaim"] if kind != "dangerous" else x["overclaim"])
        out = [f"| Score | Decider read paper → release | Experts read paper → release | Release says | Paper says |", "|---|---|---|---|---|"]
        for x in sub[:limit]:
            out.append(f"| {x['overclaim']:.2f} | {x['decider_paper']} → {x['decider_release']} | {x['expert_paper']} → {x['expert_release']} | {x['release'][:140]} | {x['paper'][:140]} |")
        if len(sub) > limit:
            out.append(f"\n*{len(sub) - limit} more in `results/misses/{kind}.csv`, {order_note}.*")
        return "\n".join(out)

    md = f"""# Every miss at the strict threshold (block > {BLOCK}), 563 expert-labelled test pairs

Generated by `python research/misses.py --wa-dir data` from the saved Decider scores. Nothing here is
hidden: the full lists are in `results/misses/`.

## Dangerous: exaggerations the gate let through ({n['dangerous']} of {exag}, {100 * n['dangerous'] / exag:.0f}%)

A false OK. Sorted with the closest calls first (highest score below the threshold). This is the
39% recall limit, item by item.

{table('dangerous', 15, 'sorted by score descending')}

## Needless: faithful releases the gate blocked ({n['needless']} of {same}, {100 * n['needless'] / same:.1f}%)

A false BLOCK, the cost of safety: a press officer would have been asked to rewrite a sentence that
experts judged faithful. Sorted with the most confident mistakes first.

{table('needless', 15, 'sorted by score descending')}

## Also flagged: releases that *downplay* their paper ({n['downplay_flagged']} of {sum(r['gold'] == 'downplays' for r in dec)})

Experts said these releases claim *less* than the paper, yet the gate flagged them as claiming more.
Counted as false flags in every rate we report.

{table('downplay_flagged', 10, 'sorted by score descending')}

## What the lists show

- **Most dangerous misses sit in the review zone.** Scores between {json.loads((R / 'calibration' / 'summary.json').read_text())['by_alpha']['0.2']['threshold']} and {BLOCK} are listed for an editor rather than blocked, so many of these are not silent.
- **The ladder reading often disagrees with the experts by one rung.** Decider tends to read a hedged causal sentence as "linked", which lowers the score.
- **Needless blocks cluster where the paper's own conclusion is hedged** ("may") and the release states the finding plainly. Experts sometimes accept that as faithful; the gate does not.
"""
    (OUT / "MISSES.md").write_text(md, encoding="utf-8")
    print(json.dumps({"dangerous": n["dangerous"], "of_exaggerates": exag, "needless": n["needless"], "of_same": same,
                      "downplay_flagged": n["downplay_flagged"], "threshold": BLOCK}, indent=1))
    return 0


if __name__ == "__main__":
    sys.exit(main())
